// A stand-in for music.youtube.com on this computer: it keeps every request
// exactly as it arrived, and answers as `respond` says. One request a
// connection, closed after the answer.
class StandIn : public QObject
{
public:
    struct Request {
        QByteArray head;   // the request line and headers, byte for byte
        QByteArray body;
        QByteArray path;
        QList<QPair<QByteArray, QByteArray>> headers;   // names in lower case

        QByteArray header(const QByteArray &name) const
        {
            for (const auto &pair : headers) {
                if (pair.first == name)
                    return pair.second;
            }
            return QByteArray();
        }
        bool has(const QByteArray &name) const
        {
            for (const auto &pair : headers) {
                if (pair.first == name)
                    return true;
            }
            return false;
        }
        QJsonObject json() const { return QJsonDocument::fromJson(body).object(); }
        bool authed() const { return has("authorization"); }
    };
    struct Answer {
        int status = 200;
        QByteArray body = "{}";
        QList<QByteArray> extra;
        bool drop = false;   // close the connection without a word
    };

    std::function<Answer(const Request &)> respond;
    QList<Request> requests;

    bool listen()
    {
        connect(&m_server, &QTcpServer::newConnection, this, &StandIn::accept);
        return m_server.listen(QHostAddress::LocalHost, 0);
    }
    QString base() const { return QStringLiteral("http://127.0.0.1:%1").arg(m_server.serverPort()); }

private:
    void accept()
    {
        while (QTcpSocket *socket = m_server.nextPendingConnection()) {
            auto buffer = std::make_shared<QByteArray>();
            connect(socket, &QTcpSocket::disconnected, socket, &QObject::deleteLater);
            connect(socket, &QTcpSocket::readyRead, this, [this, socket, buffer]() {
                *buffer += socket->readAll();
                handle(socket, *buffer);
            });
        }
    }

    void handle(QTcpSocket *socket, QByteArray &buffer)
    {
        const int end = int(buffer.indexOf("\r\n\r\n"));
        if (end < 0)
            return;
        Request request;
        request.head = buffer.left(end + 4);
        const QList<QByteArray> lines = buffer.left(end).split('\n');
        const QList<QByteArray> first = lines.value(0).trimmed().split(' ');
        request.path = first.value(1);
        for (int i = 1; i < lines.size(); ++i) {
            const QByteArray line = lines.at(i).trimmed();
            const int colon = int(line.indexOf(':'));
            if (colon > 0)
                request.headers.append({ line.left(colon).trimmed().toLower(), line.mid(colon + 1).trimmed() });
        }
        const int length = request.header("content-length").toInt();
        if (buffer.size() < end + 4 + length)
            return;
        request.body = buffer.mid(end + 4, length);
        buffer.clear();
        requests.append(request);

        const Answer answer = respond ? respond(request) : Answer();
        if (answer.drop) {
            socket->abort();
            return;
        }
        const QByteArray reason = answer.status == 200 ? "OK" : answer.status == 400 ? "Bad Request"
                                : answer.status == 401 ? "Unauthorized" : answer.status == 403 ? "Forbidden"
                                                                                                : "Error";
        QByteArray out = "HTTP/1.1 " + QByteArray::number(answer.status) + ' ' + reason + "\r\n"
                         "Content-Type: application/json; charset=UTF-8\r\n"
                         "Content-Length: " + QByteArray::number(answer.body.size()) + "\r\n"
                         "Connection: close\r\n";
        for (const QByteArray &line : answer.extra)
            out += line + "\r\n";
        out += "\r\n" + answer.body;
        socket->write(out);
        socket->disconnectFromHost();
    }

    QTcpServer m_server;
};

// Every message logged while the test runs, whatever its level, to show no
// cookie value is ever among them.
QStringList *g_captured = nullptr;
QtMessageHandler g_previousHandler = nullptr;

void captureMessage(QtMsgType type, const QMessageLogContext &context, const QString &message)
{
    if (g_captured)
        g_captured->append(message);
    if (g_previousHandler)
        g_previousHandler(type, context, message);
}

QByteArray trackingAnswer(const QByteArray &loggedIn)
{
    const QByteArray params = loggedIn.isEmpty()
        ? QByteArray(R"({"key":"e","value":"1"})")
        : R"({"key":"logged_in","value":")" + loggedIn + R"("},{"key":"e","value":"1"})";
    return R"({"responseContext":{"serviceTrackingParams":[{"service":"GFEEDBACK","params":[)" + params
           + R"(]}]},"contents":{}})";
}

const QByteArray kSignedOutMenu =
    R"({"actions":[{"openPopupAction":{"popup":{"multiPageMenuRenderer":{"sections":[]}}}}]})";

QByteArray menuAnswer(const QString &name)
{
    return R"({"actions":[{"openPopupAction":{"popup":{"multiPageMenuRenderer":{"header":{"activeAccountHeaderRenderer":)"
           R"({"accountName":{"runs":[{"text":")" + name.toUtf8() + R"("}]},"channelHandle":{"runs":[{"text":"@monolisttest"}]}}}}}}}]})";
}

struct Answered {
    bool done = false;
    QJsonObject root;
    QString error;
};

Answered browseNow(InnerTube &tube, const QString &browseId, InnerTube::Auth auth)
{
    auto result = std::make_shared<Answered>();
    tube.browse(browseId, [result](const QJsonObject &root, const QString &error) {
        result->done = true;
        result->root = root;
        result->error = error;
    }, auth);
    waitUntil([result]() { return result->done; }, 20000);
    return *result;
}

// The settings table holds no cookie value, whatever key it might be under.
QStringList settingsLeaks()
{
    QStringList found;
    QSqlQuery q(AppDatabase::connection());
    q.exec(QStringLiteral("SELECT key, value FROM settings"));
    while (q.next()) {
        if (!leaks(q.value(1).toString()).isEmpty())
            found << q.value(0).toString();
    }
    return found;
}

// Everything but the request line: what varies between two identical calls
// is only the path, when the browse ids differ.
QByteArray withoutRequestLine(const QByteArray &head)
{
    return head.mid(head.indexOf("\r\n"));
}

