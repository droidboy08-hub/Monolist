Cookie find(const QList<Cookie> &cookies, const QByteArray &name)
{
    for (const Cookie &cookie : cookies) {
        if (cookie.name == name)
            return cookie;
    }
    return Cookie();
}

bool has(const QList<Cookie> &cookies, const QByteArray &name)
{
    for (const Cookie &cookie : cookies) {
        if (cookie.name == name)
            return true;
    }
    return false;
}

bool same(const Cookie &a, const Cookie &b)
{
    return a.name == b.name && a.value == b.value && a.domain == b.domain && a.hostOnly == b.hostOnly
           && a.path == b.path && a.expires == b.expires && a.secure == b.secure && a.httpOnly == b.httpOnly;
}

bool sameJar(const QList<Cookie> &a, const QList<Cookie> &b)
{
    if (a.size() != b.size())
        return false;
    for (int i = 0; i < a.size(); ++i) {
        if (!same(a.at(i), b.at(i)))
            return false;
    }
    return true;
}

QString counts(const Result &r)
{
    return QStringLiteral("read %1, kept %2, other sites %3, elsewhere %4, expired %5, duplicates %6, "
                          "unreadable %7, spaced %8")
        .arg(r.read).arg(r.cookies.size()).arg(r.otherSites).arg(r.elsewhere).arg(r.expired)
        .arg(r.duplicates).arg(r.unreadable).arg(r.spaced);
}

// Which fixture values a piece of text gives away; empty when none.
QStringList leaks(const QString &text)
{
    QStringList found;
    for (const char *value : kValues) {
        if (text.contains(QLatin1String(value)))
            found << QString::fromLatin1(value).left(8) + QStringLiteral("...");
    }
    return found;
}

// Runs the event loop until `done` holds or `timeoutMs` passes.
bool waitUntil(const std::function<bool()> &done, int timeoutMs)
{
    if (done())
        return true;
    QEventLoop loop;
    QTimer poll;
    poll.setInterval(10);
    QObject::connect(&poll, &QTimer::timeout, &loop, [&]() {
        if (done())
            loop.quit();
    });
    QTimer::singleShot(timeoutMs, &loop, &QEventLoop::quit);
    poll.start();
    loop.exec();
    return done();
}

void settle(int ms)
{
    QEventLoop loop;
    QTimer::singleShot(ms, &loop, &QEventLoop::quit);
    loop.exec();
}

