// One audio format as /player lists it, but for its URL.
struct Listed {
    int itag;
    const char *codecs;   // the mimeType's codecs=
    int sampleRate;
    int peak;             // bitrate
    int average;          // averageBitrate
    qint64 length;        // contentLength
};

