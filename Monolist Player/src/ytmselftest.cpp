int runYtmSessionSelfTest(Library *library)
{
    Checks t("ytm");
    if (qEnvironmentVariableIsEmpty("MONOLIST_DATA_DIR")) {
        t.check(false, QStringLiteral("MONOLIST_DATA_DIR is set"),
                QStringLiteral("refusing to run: this test replaces the stored YouTube Music session"));
        return t.finish();
    }
    const QString secretName = QStringLiteral("ytmusic.cookies");
    const QString nameKey = QStringLiteral("ytmusic.account_name");
    const bool storeHere = SecretStore::available();
    t.note(storeHere ? QStringLiteral("secret store: ") + SecretStore::backendName()
                     : QStringLiteral("no secret store here (") + SecretStore::unavailableReason()
                           + QStringLiteral("): the session is kept in memory, and the restart is skipped"));

    QStringList captured;
    g_captured = &captured;
    g_previousHandler = qInstallMessageHandler(captureMessage);

    StandIn standIn;
    if (!t.check(standIn.listen(), QStringLiteral("a stand-in server on this computer"))) {
        qInstallMessageHandler(g_previousHandler);
        g_captured = nullptr;
        return t.finish();
    }
    InnerTube::setTestServer(standIn.base());
    t.note(QStringLiteral("every request goes to ") + standIn.base() + QStringLiteral(", none to YouTube"));
    const QByteArray origin = standIn.base().toUtf8();

    int regionDrops = 0;
    QString dropped;
    InnerTube::setRegion(QString());
    InnerTube::setRegionRejectedHandler([&regionDrops, &dropped](const QString &code) {
        ++regionDrops;
        dropped = code;
    });

    // How the stand-in answers, set as each step needs.
    int authedStatus = 200;
    QByteArray homeLoggedIn = "1";
    bool dropAll = false;
    bool refuseJapan = false;
    standIn.respond = [&](const StandIn::Request &request) {
        StandIn::Answer answer;
        if (dropAll) {
            answer.drop = true;
            return answer;
        }
        const bool authed = request.authed();
        const QJsonObject body = request.json();
        const QString gl = body.value(QStringLiteral("context")).toObject().value(QStringLiteral("client"))
                               .toObject().value(QStringLiteral("gl")).toString();
        if (authed && authedStatus != 200) {
            answer.status = authedStatus;
            answer.body = R"({"error":{"code":)" + QByteArray::number(authedStatus) + R"(,"status":"REFUSED"}})";
            return answer;
        }
        if (!authed && refuseJapan && gl == QLatin1String("JP")) {
            answer.status = 400;
            answer.body = R"({"error":{"code":400,"status":"INVALID_ARGUMENT"}})";
            return answer;
        }
        if (!authed)
            answer.extra << "Set-Cookie: ANONTEST=anon; Path=/";
        if (request.path.contains("account/account_menu")) {
            answer.body = authed ? menuAnswer(QStringLiteral("Monolist Test")) : kSignedOutMenu;
        } else {
            answer.body = trackingAnswer(authed ? homeLoggedIn : QByteArray("0"));
            if (authed && body.value(QStringLiteral("browseId")).toString() == QLatin1String("FEtest_rotate")) {
                answer.extra << "Set-Cookie: SIDCC=TESTROTATED-sidcc; Domain=.youtube.com; Path=/; Secure; HttpOnly"
                             << "Set-Cookie: ROTATETEST=TESTROTATED-new; Path=/";
            }
        }
        return answer;
    };

    // A clean slate.
    SecretStore::remove(secretName);
    library->setSetting(nameKey, QString());
    const QByteArray fixture = QByteArray(netscapeFixture()).replace("\n", "\r\n");
    const Result expected = CookieImport::parse(fixture);
    t.check(expected.ok(), QStringLiteral("the fixture is a session"), expected.error);
    const QByteArray expectedCookie = CookieImport::header(expected.cookies);

    // — 1. signed out, as before —
    InnerTube consumer;   // stands for Catalog, Lyrics and the rest
    const Answered first = browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::Anonymous);
    t.check(first.done && first.error.isEmpty(), QStringLiteral("an anonymous call is answered"), first.error);
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::Anonymous);
    const StandIn::Request baseline = standIn.requests.last();
    t.check(baseline.header("cookie") == "ANONTEST=anon",
            QStringLiteral("the anonymous jar works as before: its own cookie goes back"), QString::fromLatin1(baseline.header("cookie")));
    {
        // What the code sets, and what Qt adds by itself; nothing else.
        const QList<QByteArray> allowed = { "host", "content-type", "content-length", "user-agent", "origin", "referer",
                                            "cookie", "connection", "accept-encoding", "accept-language" };
        QStringList extra;
        for (const auto &pair : baseline.headers) {
            if (!allowed.contains(pair.first))
                extra << QString::fromLatin1(pair.first);
        }
        t.check(extra.isEmpty() && !baseline.authed() && !baseline.has("x-origin") && !baseline.has("x-goog-authuser"),
                QStringLiteral("an anonymous call carries nothing of an account"), extra.join(QStringLiteral(", ")));
        QStringList names;
        for (const auto &pair : baseline.headers)
            names << QString::fromLatin1(pair.first);
        t.note(QStringLiteral("anonymous headers: ") + names.join(QStringLiteral(", ")));
    }
    const auto sameAsBaseline = [&baseline](const StandIn::Request &request) {
        return request.head == baseline.head && request.body == baseline.body;
    };
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::IfSignedIn);
    t.check(sameAsBaseline(standIn.requests.last()),
            QStringLiteral("IfSignedIn with no account hook: byte for byte the anonymous request"));

    auto session = std::make_unique<YtmSession>(library);
    YtmSession::Timing timing;
    timing.launchCheckMs = 100;
    timing.recheckMs = 300;
    timing.retryMinMs = 10 * 60 * 1000;   // never within the test
    timing.saveDelayMs = 300;
    session->setTiming(timing);
    QStringList outcomes;
    const auto follow = [&outcomes](YtmSession *s) {
        QObject::connect(s, &YtmSession::checked, s, [&outcomes](const QString &outcome) { outcomes << outcome; });
    };
    follow(session.get());
    session->start();
    t.check(session->state() == QLatin1String("signedOut"), QStringLiteral("nothing stored: signed out"), session->state());
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::IfSignedIn);
    t.check(sameAsBaseline(standIn.requests.last()),
            QStringLiteral("IfSignedIn while signed out: byte for byte the anonymous request"));

    // — 2. import, and the check —
    const auto waitVerdict = [&outcomes](int before) {
        return waitUntil([&outcomes, before]() { return outcomes.size() > before; }, 15000);
    };
    int requestsBefore = int(standIn.requests.size());
    int outcomesBefore = int(outcomes.size());
    t.check(session->importText(QString::fromUtf8(fixture)) && session->state() == QLatin1String("checking"),
            QStringLiteral("a pasted cookies.txt imports, and is being checked"), session->importError());
    waitVerdict(outcomesBefore);
    t.check(session->state() == QLatin1String("active") && session->accountName() == QLatin1String("Monolist Test"),
            QStringLiteral("logged_in=1 and the account menu's name: active, as Monolist Test"),
            session->state() + QStringLiteral(" / ") + session->accountName());
    t.check(library->settingValue(nameKey) == QLatin1String("Monolist Test"),
            QStringLiteral("the name, and only the name, is in settings"));
    {
        int menu = 0;
        int home = 0;
        bool headersRight = true;
        QString why;
        static const QRegularExpression stamp(QStringLiteral("^SAPISIDHASH (\\d+)_"));
        for (int i = requestsBefore; i < standIn.requests.size(); ++i) {
            const StandIn::Request &request = standIn.requests.at(i);
            menu += request.path.contains("account/account_menu");
            home += request.json().value(QStringLiteral("browseId")).toString() == QLatin1String("FEmusic_home");
            const QRegularExpressionMatch match = stamp.match(QString::fromLatin1(request.header("authorization")));
            const QByteArray authorization = match.hasMatch()
                ? YtmSession::authorization(expected.cookies, match.captured(1).toLongLong(), origin) : QByteArray();
            if (request.header("cookie") != expectedCookie)
                why += QStringLiteral(" cookie");
            if (!match.hasMatch() || request.header("authorization") != authorization)
                why += QStringLiteral(" authorization");
            if (request.header("x-origin") != origin || request.header("x-goog-authuser") != "0")
                why += QStringLiteral(" x-origin/x-goog-authuser");
            headersRight = headersRight && why.isEmpty();
        }
        t.check(menu == 1 && home == 1, QStringLiteral("the check asks account_menu and FEmusic_home, once each"),
                QStringLiteral("%1 and %2").arg(menu).arg(home));
        t.check(headersRight, QStringLiteral("both carry exactly the jar's Cookie (not the anonymous jar's), the three "
                                             "SID hashes, X-Origin and X-Goog-AuthUser: 0"), why);
    }
    if (storeHere) {
        QByteArray stored;
        QList<Cookie> jar;
        const bool read = SecretStore::read(secretName, &stored) == SecretStore::Status::Ok;
        t.check(read && CookieImport::fromJson(stored, &jar) && sameJar(jar, expected.cookies),
                QStringLiteral("the jar is kept in the secret store (%1 bytes of JSON)").arg(stored.size()));
        const QString folder = SecretStore::folderPath();
        if (!folder.isEmpty()) {
            QFile file(QDir(folder).filePath(QStringLiteral("ytmusic.cookies.dpapi")));
            const QByteArray onDisk = file.open(QIODevice::ReadOnly) ? file.readAll() : QByteArray();
            t.check(!onDisk.isEmpty() && !onDisk.contains("TESTSAPISID123") && !onDisk.contains("LOGIN_INFO"),
                    QStringLiteral("the file on disk (%1 bytes) holds neither names nor values in the clear").arg(onDisk.size()));
        }
    }
    t.check(settingsLeaks().isEmpty(), QStringLiteral("no cookie value anywhere in the settings table"),
            settingsLeaks().join(QStringLiteral(", ")));

    // — 3. only the calls that ask carry it —
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::Anonymous);
    t.check(sameAsBaseline(standIn.requests.last()),
            QStringLiteral("while signed in, an anonymous call is byte for byte what it was signed out"));
    const Answered rotate = browseNow(consumer, QStringLiteral("FEtest_rotate"), InnerTube::Auth::IfSignedIn);
    {
        const StandIn::Request &request = standIn.requests.last();
        t.check(rotate.error.isEmpty() && request.authed() && request.header("cookie") == expectedCookie
                    && withoutRequestLine(request.head) != withoutRequestLine(baseline.head),
                QStringLiteral("an IfSignedIn call carries the account, and none of the anonymous jar"), rotate.error);
    }
    t.check(find(session->jar(), "SIDCC").value == "TESTROTATED-sidcc" && find(session->jar(), "SIDCC").domain == QLatin1String("youtube.com")
                && has(session->jar(), "ROTATETEST") && find(session->jar(), "ROTATETEST").hostOnly
                && session->savePending(),
            QStringLiteral("Set-Cookie on its answer rotates the session's jar (SIDCC replaced, ROTATETEST added)"));
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::Anonymous);
    t.check(sameAsBaseline(standIn.requests.last()),
            QStringLiteral("and none of it lands in the anonymous jar: the next anonymous call is unchanged"));
    waitUntil([&session]() { return !session->savePending(); }, 5000);
    if (storeHere) {
        QByteArray stored;
        QList<Cookie> jar;
        SecretStore::read(secretName, &stored);
        CookieImport::fromJson(stored, &jar);
        t.check(find(jar, "SIDCC").value == "TESTROTATED-sidcc" && has(jar, "ROTATETEST"),
                QStringLiteral("the rotated jar is saved after the delay"));
    }

    // — 4. a 400 on a call with the account never touches the country —
    InnerTube::setRegion(QStringLiteral("JP"));
    authedStatus = 400;
    requestsBefore = int(standIn.requests.size());
    const Answered refused400 = browseNow(consumer, QStringLiteral("FEtest_400"), InnerTube::Auth::IfSignedIn);
    authedStatus = 200;
    {
        const bool two = standIn.requests.size() == requestsBefore + 2;
        const bool firstAuthed = two && standIn.requests.at(requestsBefore).authed();
        const bool thenAnonymous = two && !standIn.requests.at(requestsBefore + 1).authed()
                                   && standIn.requests.at(requestsBefore + 1).header("cookie") == "ANONTEST=anon";
        t.check(refused400.error.isEmpty() && firstAuthed && thenAnonymous,
                QStringLiteral("a 400 with the account: asked again without it, and answered"),
                QStringLiteral("%1 requests; %2").arg(standIn.requests.size() - requestsBefore).arg(refused400.error));
        t.check(InnerTube::region() == QLatin1String("JP") && regionDrops == 0,
                QStringLiteral("the chosen country is kept, and Library::dropRegion is never called"),
                QStringLiteral("region %1, %2 drops").arg(InnerTube::region()).arg(regionDrops));
        t.check(session->state() == QLatin1String("active") && !session->jar().isEmpty(),
                QStringLiteral("a 400 is not a verdict on the session: still active"), session->state());
    }

    // — 5. a country refused for everyone is still dropped, as before —
    refuseJapan = true;
    const Answered refusedRegion = browseNow(consumer, QStringLiteral("FEtest_region"), InnerTube::Auth::Anonymous);
    refuseJapan = false;
    t.check(refusedRegion.error.isEmpty() && regionDrops == 1 && dropped == QLatin1String("JP")
                && InnerTube::region() == InnerTube::systemRegion(),
            QStringLiteral("an anonymous 400 from a refused country: dropped, told, and asked again (unchanged)"),
            QStringLiteral("%1 drops of %2; %3").arg(regionDrops).arg(dropped, refusedRegion.error));
    InnerTube::setRegion(QString());

    // — 6. 403: the session is over —
    const quint64 oldSession = session->session();
    authedStatus = 403;
    const Answered refused403 = browseNow(consumer, QStringLiteral("FEtest_403"), InnerTube::Auth::IfSignedIn);
    authedStatus = 200;
    t.check(refused403.error.isEmpty() && !standIn.requests.last().authed(),
            QStringLiteral("a 403 with the account: asked again without it, and answered"), refused403.error);
    t.check(session->state() == QLatin1String("rejected") && session->jar().isEmpty()
                && session->statusLine().contains(QLatin1String("ended")),
            QStringLiteral("and the session is refused: rejected, the cookies dropped"), session->state());
    if (storeHere) {
        QByteArray gone;
        t.check(SecretStore::read(secretName, &gone) == SecretStore::Status::NotFound,
                QStringLiteral("the stored copy is deleted"));
    }
    t.check(library->settingValue(nameKey) == QLatin1String("Monolist Test"),
            QStringLiteral("the name stays, to say whose session ended"));
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::IfSignedIn);
    t.check(sameAsBaseline(standIn.requests.last()),
            QStringLiteral("IfSignedIn after the refusal: byte for byte the anonymous request"));
    {
        const QNetworkCookie late(QByteArrayLiteral("SIDCC"), QByteArrayLiteral("TESTROTATED-sidcc"));
        session->absorbCookies(oldSession, { late });
        session->reportRejected(oldSession, 401);
        t.check(session->jar().isEmpty() && session->state() == QLatin1String("rejected"),
                QStringLiteral("a late answer for the old session changes nothing"));
    }

    // — 7. logged_in=0 is believed the second time —
    homeLoggedIn = "0";
    outcomesBefore = int(outcomes.size());
    requestsBefore = int(standIn.requests.size());
    session->importText(QString::fromUtf8(kHeader));
    waitVerdict(outcomesBefore);
    t.check(outcomes.value(outcomesBefore) == QLatin1String("again") && session->state() == QLatin1String("checking"),
            QStringLiteral("a first logged_in=0: asked once more, still checking"), outcomes.value(outcomesBefore));
    waitVerdict(outcomesBefore + 1);
    {
        int homes = 0;
        for (int i = requestsBefore; i < standIn.requests.size(); ++i)
            homes += standIn.requests.at(i).json().value(QStringLiteral("browseId")).toString() == QLatin1String("FEmusic_home");
        t.check(outcomes.value(outcomesBefore + 1) == QLatin1String("rejected") && session->state() == QLatin1String("rejected")
                    && homes == 2,
                QStringLiteral("a second logged_in=0: rejected, after two checks"),
                QStringLiteral("%1, %2 checks").arg(outcomes.value(outcomesBefore + 1)).arg(homes));
    }
    homeLoggedIn = "1";

    // — 8. no answer: kept, not believed either way —
    dropAll = true;
    outcomesBefore = int(outcomes.size());
    session->importText(QString::fromUtf8(fixture));
    waitVerdict(outcomesBefore);
    dropAll = false;
    {
        QByteArray cookie;
        QByteArray authorization;
        const bool ifSignedIn = session->authHeaders(InnerTube::Auth::IfSignedIn, origin, &cookie, &authorization) != 0;
        const bool checking = session->authHeaders(InnerTube::Auth::Checking, origin, &cookie, &authorization) != 0;
        t.check(outcomes.value(outcomesBefore) == QLatin1String("unreachable") && session->state() == QLatin1String("unreachable")
                    && !session->jar().isEmpty() && !ifSignedIn && checking,
                QStringLiteral("no answer: unreachable, the session kept but not used; only a check may carry it"),
                session->state());
        QByteArray stored;
        if (storeHere)
            t.check(SecretStore::read(secretName, &stored) == SecretStore::Status::Ok, QStringLiteral("and still stored"));
    }
    outcomesBefore = int(outcomes.size());
    session->checkNow();
    waitVerdict(outcomesBefore);
    t.check(session->state() == QLatin1String("active"), QStringLiteral("asked again once it answers: active"), session->state());

    // — 9. a restart —
    if (storeHere) {
        const QList<Cookie> before = session->jar();
        session.reset();
        session = std::make_unique<YtmSession>(library);
        session->setTiming(timing);
        follow(session.get());
        outcomesBefore = int(outcomes.size());
        session->start();
        t.check(session->state() == QLatin1String("checking") && sameJar(session->jar(), before)
                    && session->accountName() == QLatin1String("Monolist Test"),
                QStringLiteral("a restart restores the session, and checks it before using it"), session->state());
        waitVerdict(outcomesBefore);
        t.check(session->state() == QLatin1String("active"), QStringLiteral("then active"), session->state());
    }

    // — 10. sign out —
    session->signOut();
    {
        QByteArray gone;
        t.check(session->state() == QLatin1String("signedOut") && session->jar().isEmpty()
                    && library->settingValue(nameKey).isEmpty()
                    && (!storeHere || SecretStore::read(secretName, &gone) == SecretStore::Status::NotFound),
                QStringLiteral("sign out: the stored copy deleted, the name forgotten"), session->state());
    }
    browseNow(consumer, QStringLiteral("FEtest_anon"), InnerTube::Auth::IfSignedIn);
    t.check(sameAsBaseline(standIn.requests.last()),
            QStringLiteral("IfSignedIn after sign-out: byte for byte the anonymous request"));

    // — 11. a file, and the offer to delete it —
    {
        const QString folder = QFileInfo(AppDatabase::databaseFilePath()).absolutePath();
        const QString deletePath = QDir(folder).filePath(QStringLiteral("cookies-selftest.txt"));
        const QString keepPath = QDir(folder).filePath(QStringLiteral("cookies-selftest-keep.txt"));
        for (const QString &path : { deletePath, keepPath }) {
            QFile file(path);
            if (!file.open(QIODevice::WriteOnly | QIODevice::Truncate) || file.write(fixture) != fixture.size())
                t.note(QStringLiteral("could not write the fixture file ") + QFileInfo(path).fileName());
        }
        outcomesBefore = int(outcomes.size());
        t.check(session->importFile(QUrl::fromLocalFile(deletePath))
                    && session->importedFileName() == QLatin1String("cookies-selftest.txt"),
                QStringLiteral("a file imports, and Monolist offers to delete it"), session->importError());
        waitVerdict(outcomesBefore);
        t.check(QFileInfo::exists(deletePath), QStringLiteral("the file is left where it was until the user answers"));
        t.check(session->deleteImportedFile() && !QFileInfo::exists(deletePath) && session->importedFileName().isEmpty(),
                QStringLiteral("\"delete the file\": it is gone, and the offer with it"));

        const bool refused = session->importText(QStringLiteral("SAPISID=TESTSAPISID123; SID=TESTVAL-sid-youtube-6"));
        t.check(!refused && session->importError().contains(QLatin1String("LOGIN_INFO"))
                    && session->state() == QLatin1String("active") && session->importedFileName().isEmpty(),
                QStringLiteral("a refused import says why and leaves the session as it was"), session->importError());

        outcomesBefore = int(outcomes.size());
        session->importFile(QUrl::fromLocalFile(keepPath));
        waitVerdict(outcomesBefore);
        session->keepImportedFile();
        t.check(QFileInfo::exists(keepPath) && session->importedFileName().isEmpty() && session->importError().isEmpty(),
                QStringLiteral("\"keep it\": the file stays, and the offer goes"));
        // The test's own fixture, not a user's file.
        QFile::remove(keepPath);
        session->signOut();
    }

    // — 12. the log —
    {
        g_captured = nullptr;
        qInstallMessageHandler(g_previousHandler);
        QStringList found;
        bool namesLogged = false;
        for (const QString &line : std::as_const(captured)) {
            found << leaks(line);
            namesLogged = namesLogged || (line.startsWith(QLatin1String("ytmusic: imported")) && line.contains(QLatin1String("LOGIN_INFO")));
        }
        t.check(found.isEmpty(), QStringLiteral("none of %1 lines logged during the test holds a cookie value or a hash")
                                     .arg(captured.size()), found.join(QStringLiteral(", ")));
        t.check(namesLogged, QStringLiteral("while the names are logged, for diagnosis"));
    }

    session.reset();
    SecretStore::remove(secretName);
    library->setSetting(nameKey, QString());
    InnerTube::setRegionRejectedHandler({});
    InnerTube::setTestServer(QString());
    settle(50);
    return t.finish();
}
