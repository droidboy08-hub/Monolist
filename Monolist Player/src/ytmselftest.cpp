int runCookieImportSelfTest()
{
    Checks t("cookies");
    constexpr qint64 kNow = 1790000000;   // 2026-09-21, fixed so expiry is the same on every run
    QStringList messages;                 // every error and summary, for the leak check at the end
    const auto keep = [&messages](const Result &r) {
        messages << r.error << r.summary();
        return r;
    };

    // — cookies.txt —
    const QByteArray netscape = netscapeFixture();
    const Result lf = keep(CookieImport::parse(netscape, kNow));
    t.check(lf.ok() && lf.format == Format::Netscape, QStringLiteral("a cookies.txt file (LF) is a signed-in session"),
            lf.error);
    t.check(lf.read == kFixtureCookies && lf.cookies.size() == 19 && lf.otherSites == 2 && lf.elsewhere == 2
                && lf.expired == 1 && lf.duplicates == 1 && lf.unreadable == 1 && lf.spaced == 0,
            QStringLiteral("counts: 25 read, 19 kept, 2 other sites, 2 elsewhere on YouTube, 1 expired, 1 duplicate, "
                           "1 unreadable"), counts(lf));
    t.check(lf.info.isEmpty(), QStringLiteral("a cookies.txt file says nothing of the session beside its cookies"));
    {
        QStringList expected;
        for (const char *name : kKeptNames)
            expected << QString::fromLatin1(name);
        t.check(CookieImport::names(lf.cookies) == expected, QStringLiteral("the names kept, in the order read"),
                CookieImport::names(lf.cookies).join(QLatin1Char(',')));
    }
    t.note(QStringLiteral("summary: ") + lf.summary());
    {
        const Cookie login = find(lf.cookies, "LOGIN_INFO");
        t.check(login.value == "TESTVAL-login-info-2" && login.httpOnly && login.secure && login.domain == QLatin1String("youtube.com")
                    && !login.hostOnly && login.expires == 1830000000,
                QStringLiteral("#HttpOnly_ lines are cookies: LOGIN_INFO kept, HttpOnly, .youtube.com"));
        t.check(!find(lf.cookies, "SAPISID").httpOnly && find(lf.cookies, "HSID").httpOnly
                    && !find(lf.cookies, "HSID").secure,
                QStringLiteral("HttpOnly and Secure are read per line"));
        int sidccs = 0;
        bool bothSidcc = true;
        for (const Cookie &cookie : lf.cookies) {
            if (cookie.name != "SIDCC")
                continue;
            ++sidccs;
            bothSidcc = bothSidcc
                        && (cookie.domain == QLatin1String("music.youtube.com")
                                ? cookie.hostOnly && cookie.value == "TESTVAL-sidcc-music-11"
                                : cookie.domain == QLatin1String("youtube.com") && !cookie.hostOnly
                                      && cookie.value == "TESTVAL-sidcc-9");
        }
        t.check(sidccs == 2 && bothSidcc,
                QStringLiteral("SIDCC on .youtube.com and on music.youtube.com: two cookies, both kept (each host "
                               "is sent its own below)"));
        t.check(find(lf.cookies, "SID").value == "TESTVAL-sid-youtube-6",
                QStringLiteral("SID on google.com is left out, and YouTube's own copy kept"));
        t.check(find(lf.cookies, "APISID").value == "TESTVAL-apisid-3",
                QStringLiteral("the same cookie twice (name, domain and path): the first stays"));
        t.check(find(lf.cookies, "YSC").expires == 0, QStringLiteral("a session cookie (expiry 0) is kept"));
        t.check(has(lf.cookies, "EMPTYVAL") && find(lf.cookies, "EMPTYVAL").value.isEmpty(),
                QStringLiteral("a line of six fields is a cookie with an empty value"));
        t.check(has(lf.cookies, "WWWONLY") && has(lf.cookies, "WATCHPATH") && has(lf.cookies, "STATSONLY")
                    && has(lf.cookies, "STATSPATH"),
                QStringLiteral("www.youtube.com's own, s.youtube.com's own, /watch's and /api/stats's are kept"));
        t.check(!has(lf.cookies, "ACCOUNTSONLY") && !has(lf.cookies, "MOBILEONLY") && !has(lf.cookies, "OLDCOOKIE"),
                QStringLiteral("accounts.youtube.com's, m.youtube.com's and expired cookies are left out"));
    }

    // Line ends, and a byte-order mark.
    {
        QByteArray crlf = netscape;
        crlf.replace("\n", "\r\n");
        const Result r = keep(CookieImport::parse(crlf, kNow));
        t.check(r.ok() && sameJar(r.cookies, lf.cookies) && r.read == lf.read,
                QStringLiteral("the same file with CRLF line ends reads the same"), r.error);
        const Result bom = keep(CookieImport::parse(QByteArray("\xEF\xBB\xBF") + crlf, kNow));
        t.check(bom.ok() && sameJar(bom.cookies, lf.cookies),
                QStringLiteral("and with a UTF-8 byte-order mark in front"), bom.error);
    }

    // Expiries no whole number of seconds can hold: refused as unreadable,
    // never turned into some other time (converting them is undefined).
    {
        const QByteArray odd = netscape
                               + ".youtube.com\tTRUE\t/\tTRUE\t1e300\tHUGEEXPIRY\tTESTVAL-huge\n"
                               + ".youtube.com\tTRUE\t/\tTRUE\tinf\tINFEXPIRY\tTESTVAL-inf\n"
                               + ".youtube.com\tTRUE\t/\tTRUE\tnan\tNANEXPIRY\tTESTVAL-nan\n"
                               + ".youtube.com\tTRUE\t/\tTRUE\t9300000000000000000\tOVERFLOW\tTESTVAL-overflow\n"
                               + ".youtube.com\tTRUE\t/\tTRUE\t253402300799\tYEAR9999\tTESTVAL-9999\n";
        const Result r = keep(CookieImport::parse(odd, kNow));
        t.check(r.ok() && r.unreadable == lf.unreadable + 4 && !has(r.cookies, "HUGEEXPIRY")
                    && !has(r.cookies, "INFEXPIRY") && !has(r.cookies, "NANEXPIRY") && !has(r.cookies, "OVERFLOW")
                    && find(r.cookies, "YEAR9999").expires == 253402300799LL,
                QStringLiteral("expiries of 1e300, inf, nan and past 2^63: unreadable; the end of 9999 is kept"),
                counts(r));
    }

    // Spaces where the tabs go.
    {
        QByteArray spaced = netscape;
        spaced.replace('\t', ' ');
        const Result r = keep(CookieImport::parse(spaced, kNow));
        t.check(!r.ok() && r.format == Format::Netscape && r.spaced == kFixtureCookies && r.cookies.isEmpty()
                    && r.error.contains(QLatin1String("tabs")),
                QStringLiteral("spaces where the tabs go: refused, and it says so"), counts(r) + QStringLiteral("; ") + r.error);
        // One spaced line among good ones is skipped, and the rest still count.
        QByteArray oneSpaced = netscape;
        oneSpaced.replace(".youtube.com\tTRUE\t/\tTRUE\t1830000000\tPREF\tTESTVAL-pref-1",
                          ".youtube.com TRUE / TRUE 1830000000 PREF TESTVAL-pref-1");
        const Result mixed = keep(CookieImport::parse(oneSpaced, kNow));
        t.check(mixed.ok() && mixed.spaced == 1 && !has(mixed.cookies, "PREF")
                    && mixed.cookies.size() == lf.cookies.size() - 1,
                QStringLiteral("one spaced line among good ones is skipped, the rest kept"), counts(mixed));
    }

    // What reading #HttpOnly_ as a comment would cost.
    {
        QByteArray commented = netscape;
        commented.replace("#HttpOnly_", "# HttpOnly_");
        const Result r = keep(CookieImport::parse(commented, kNow));
        t.check(!r.ok() && r.missing.contains(QStringLiteral("LOGIN_INFO")),
                QStringLiteral("(the same file with its HttpOnly lines commented out has no LOGIN_INFO: refused)"),
                r.error);
    }

    // Not a session.
    {
        const Result noLogin = keep(CookieImport::parse(
            netscapeFixture([](const QByteArray &line) { return !line.contains("LOGIN_INFO"); }), kNow));
        t.check(!noLogin.ok() && noLogin.cookies.isEmpty() && noLogin.error.contains(QLatin1String("LOGIN_INFO")),
                QStringLiteral("no LOGIN_INFO: refused, naming it"), noLogin.error);
        const Result noSapisid = keep(CookieImport::parse(
            netscapeFixture([](const QByteArray &line) { return !line.contains("APISID\t"); }), kNow));
        t.check(!noSapisid.ok() && noSapisid.error.contains(QLatin1String("SAPISID")),
                QStringLiteral("no SAPISID, __Secure-1PAPISID or __Secure-3PAPISID: refused, naming SAPISID"),
                noSapisid.error);
        const Result googleOnly = keep(CookieImport::parse(
            netscapeFixture([](const QByteArray &line) { return !line.contains("youtube.com"); }), kNow));
        t.check(!googleOnly.ok() && googleOnly.otherSites == 2 && googleOnly.error.contains(QLatin1String("None of these")),
                QStringLiteral("google.com's cookies only: refused"), googleOnly.error);
        const Result expired = keep(CookieImport::parse(netscape, 1840000000));
        t.check(!expired.ok() && expired.error.contains(QLatin1String("LOGIN_INFO"))
                    && expired.error.contains(QLatin1String("expired")),
                QStringLiteral("the same file read after it expired: refused, saying so"), expired.error);
        // Two different mistakes, with two different remedies.
        t.check(expired.error.contains(QLatin1String("old export"))
                    && !expired.error.contains(QLatin1String("copied while signed out"))
                    && noLogin.error.contains(QLatin1String("copied while signed out"))
                    && noLogin.error.contains(QLatin1String("allowed in private windows")),
                QStringLiteral("an expired LOGIN_INFO is called an old export; a missing one, a copy made signed "
                               "out (and an extension not allowed in private windows is named)"),
                expired.error + QStringLiteral(" / ") + noLogin.error);
        const Result nothing = keep(CookieImport::parse("# Netscape HTTP Cookie File\n\n", kNow));
        t.check(!nothing.ok() && nothing.error.contains(QLatin1String("no cookies")),
                QStringLiteral("a cookies.txt file with no cookies: refused"), nothing.error);
    }

    // — the Cookie header —
    {
        const Result r = keep(CookieImport::parse(kHeader, kNow));
        t.check(r.ok() && r.format == Format::Header && r.cookies.size() == 7 && r.duplicates == 1,
                QStringLiteral("a Cookie header: 7 cookies, 1 duplicate"), counts(r) + QStringLiteral("; ") + r.error);
        const Cookie sid = find(r.cookies, "SID");
        t.check(sid.value == "TESTVAL-sid-youtube-6" && sid.domain == QLatin1String("youtube.com") && !sid.hostOnly
                    && sid.secure && sid.path == QLatin1String("/"),
                QStringLiteral("a header's cookies count as .youtube.com, path /, secure; the first SID stays"));
        const Result lower = keep(CookieImport::parse(QByteArray(kHeader).replace("Cookie:", "cookie:"), kNow));
        t.check(lower.ok() && sameJar(lower.cookies, r.cookies), QStringLiteral("\"cookie:\" in lower case"));
        const Result bare = keep(CookieImport::parse(kHeader.mid(int(qstrlen("Cookie: "))), kNow));
        t.check(bare.ok() && sameJar(bare.cookies, r.cookies), QStringLiteral("the value alone, without its name"));
        const QByteArray block = ":authority: music.youtube.com\r\naccept: */*\r\n"
                                 + QByteArray(kHeader).replace("Cookie:", "cookie:")
                                 + "\r\nuser-agent: Mozilla/5.0 (Windows NT 10.0; Win64; x64)\r\n";
        const Result headers = keep(CookieImport::parse(block, kNow));
        t.check(headers.ok() && sameJar(headers.cookies, r.cookies),
                QStringLiteral("a whole block of request headers: the cookie line is found"), headers.error);
        const Result noCookie = keep(CookieImport::parse(":authority: music.youtube.com\naccept: */*\n", kNow));
        t.check(!noCookie.ok() && noCookie.error.contains(QLatin1String("no Cookie header")),
                QStringLiteral("request headers with no cookie line: refused, saying so"), noCookie.error);
        const Result onlySecure3 = keep(CookieImport::parse(
            "LOGIN_INFO=TESTVAL-login-info-2; __Secure-3PAPISID=TESTSECURE3PAPISID789", kNow));
        t.check(onlySecure3.ok(), QStringLiteral("LOGIN_INFO and __Secure-3PAPISID without SAPISID is a session"),
                onlySecure3.error);
        const Result header = keep(CookieImport::parse("SAPISID=TESTSAPISID123; SID=TESTVAL-sid-youtube-6", kNow));
        t.check(!header.ok() && header.error.contains(QLatin1String("LOGIN_INFO")),
                QStringLiteral("a header without LOGIN_INFO: refused"), header.error);
        const Result words = keep(CookieImport::parse("hello there", kNow));
        t.check(!words.ok() && words.format == Format::Header, QStringLiteral("plain words: refused"), words.error);

        // What a copied request says of the session beside its cookies.
        const QByteArray withSession = ":authority: music.youtube.com\r\nx-goog-authuser: 1\r\nx-goog-visitor-id: "
                                       + kCopiedVisitor.toLatin1() + "\r\n"
                                       + QByteArray(kHeader).replace("Cookie:", "cookie:") + "\r\n";
        const Result session = keep(CookieImport::parse(withSession, kNow));
        t.check(session.ok() && sameJar(session.cookies, r.cookies) && session.info.authUser == 1
                    && session.info.visitorData == kCopiedVisitor && session.info.dataSyncId.isEmpty(),
                QStringLiteral("request headers copied whole: x-goog-authuser and x-goog-visitor-id are read too"),
                session.error);
        t.check(r.info.isEmpty() && bare.info.isEmpty(), QStringLiteral("a Cookie header alone says nothing more"));
        const Result odd = keep(CookieImport::parse(
            ":authority: music.youtube.com\r\nx-goog-authuser: 1a\r\nx-goog-visitor-id: two words\r\n" + kHeader, kNow));
        t.check(odd.ok() && odd.info.isEmpty(),
                QStringLiteral("an x-goog-authuser that is no number from 0 to 99, a visitor id with a space: ignored"),
                odd.error);
    }

    // — cURL —
    {
        const QByteArray bash =
            "curl 'https://music.youtube.com/youtubei/v1/browse?prettyPrint=false' \\\n"
            "  -H 'accept: */*' \\\n"
            "  -H 'content-type: application/json' \\\n"
            "  -b 'PREF=TESTVAL-pref-1; LOGIN_INFO=TESTVAL-login-info-2; SAPISID=TESTSAPISID123; "
            "__Secure-3PAPISID=TESTSECURE3PAPISID789' \\\n"
            "  -H 'origin: https://music.youtube.com' \\\n"
            "  --data-raw '{\"context\":{\"client\":{\"clientName\":\"WEB_REMIX\"}},\"browseId\":\"FEmusic_home\"}'";
        const Result r = keep(CookieImport::parse(bash, kNow));
        t.check(r.ok() && r.format == Format::Curl && CookieImport::names(r.cookies).join(QLatin1Char(','))
                    == QLatin1String("PREF,LOGIN_INFO,SAPISID,__Secure-3PAPISID")
                    && find(r.cookies, "SAPISID").value == "TESTSAPISID123",
                QStringLiteral("cURL (bash), cookies in -b, lines continued with a backslash"),
                counts(r) + QStringLiteral("; ") + r.error);
        QByteArray crlf = bash;
        crlf.replace("\n", "\r\n");
        const Result rc = keep(CookieImport::parse(crlf, kNow));
        t.check(rc.ok() && sameJar(rc.cookies, r.cookies), QStringLiteral("the same with CRLF line ends"), rc.error);

        const QByteArray header = "curl 'https://music.youtube.com/youtubei/v1/browse' -X POST "
                                  "-H 'User-Agent: Mozilla/5.0' -H '" + kHeader + "' --data-raw '{}'";
        const Result rh = keep(CookieImport::parse(header, kNow));
        t.check(rh.ok() && rh.cookies.size() == 7, QStringLiteral("cURL with -H 'Cookie: ...' (Firefox's copy)"),
                counts(rh) + QStringLiteral("; ") + rh.error);

        const QByteArray withSession = "curl 'https://music.youtube.com/youtubei/v1/browse?prettyPrint=false' \\\n"
                                       "  -H 'x-goog-authuser: 2' \\\n"
                                       "  -H 'X-Goog-Visitor-Id: " + kCopiedVisitor.toLatin1() + "' \\\n"
                                       "  -b 'LOGIN_INFO=TESTVAL-login-info-2; SAPISID=TESTSAPISID123'";
        const Result rs = keep(CookieImport::parse(withSession, kNow));
        t.check(rs.ok() && rs.info.authUser == 2 && rs.info.visitorData == kCopiedVisitor,
                QStringLiteral("cURL: the x-goog-authuser and x-goog-visitor-id headers are read too"), rs.error);
        t.check(r.info.isEmpty() && rh.info.isEmpty(), QStringLiteral("a cURL copy without them says nothing more"));

        // $'...': what Chrome writes when a header holds a quote or a '!'.
        const QByteArray ansi = "curl 'https://music.youtube.com/' -H $'cookie: PREF=it\\'s; "
                                "LOGIN_INFO=TESTVAL\\u0021x; SAPISID=TESTSAPISID123'";
        const Result ra = keep(CookieImport::parse(ansi, kNow));
        t.check(ra.ok() && find(ra.cookies, "PREF").value == "it's" && find(ra.cookies, "LOGIN_INFO").value == "TESTVAL!x",
                QStringLiteral("cURL with $'...' quoting: \\' and \\u0021 decoded"), ra.error);

        // cmd.exe: Chrome's "Copy as cURL (cmd)".
        const QByteArray cmd =
            "curl ^\"https://music.youtube.com/youtubei/v1/browse?prettyPrint=false^\" ^\r\n"
            "  -H ^\"accept: */*^\" ^\r\n"
            "  -b ^\"PREF=TESTVAL-pref-1; LOGIN_INFO=TESTVAL-login^%^&x; SAPISID=TESTSAPISID123^\" ^\r\n"
            "  --data-raw ^\"^{^\\^\"context^\\^\":1^}^\"";
        const Result rw = keep(CookieImport::parse(cmd, kNow));
        t.check(rw.ok() && find(rw.cookies, "LOGIN_INFO").value == "TESTVAL-login%&x" && rw.cookies.size() == 3,
                QStringLiteral("cURL (cmd): carets and ^\" undone"), counts(rw) + QStringLiteral("; ") + rw.error);
        const QStringList words = CookieImport::commandWords(QString::fromUtf8(cmd), true);
        t.check(words.size() == 8 && words.last() == QLatin1String("{\"context\":1}"),
                QStringLiteral("cmd: the escaped JSON body decodes to its quotes"), words.join(QLatin1Char('|')));

        const Result file = keep(CookieImport::parse("curl 'https://music.youtube.com/' -b cookies.txt", kNow));
        t.check(!file.ok() && file.error.contains(QLatin1String("file")),
                QStringLiteral("cURL that reads its cookies from a file: refused, saying so"), file.error);
        const Result none = keep(CookieImport::parse("curl 'https://music.youtube.com/' -H 'accept: */*'", kNow));
        t.check(!none.ok() && none.error.contains(QLatin1String("no cookies")),
                QStringLiteral("cURL with no cookies: refused"), none.error);
    }

    // — the shells' words —
    {
        const QStringList posix = CookieImport::commandWords(
            QStringLiteral("a 'b c' \"d \\\"e\\\"\" $'f\\ng' h\\ i \\\n j"), false);
        t.check(posix == QStringList{ QStringLiteral("a"), QStringLiteral("b c"), QStringLiteral("d \"e\""),
                                      QStringLiteral("f\ng"), QStringLiteral("h i"), QStringLiteral("j") },
                QStringLiteral("bash: '...', \"...\", $'...', backslash escapes and continuations"),
                posix.join(QLatin1Char('|')));
        const QStringList windows = CookieImport::commandWords(
            QStringLiteral("curl ^\"a b^\" ^\"c\\^\"d^\" ^\"e\\\\f^\""), true);
        t.check(windows == QStringList{ QStringLiteral("curl"), QStringLiteral("a b"), QStringLiteral("c\"d"),
                                        QStringLiteral("e\\\\f") },
                QStringLiteral("cmd: carets, then the C runtime's quotes and backslashes"),
                windows.join(QLatin1Char('|')));
    }

    // — other things people paste —
    {
        const Result json = keep(CookieImport::parse(
            "[{\"domain\":\".youtube.com\",\"name\":\"SAPISID\",\"value\":\"TESTSAPISID123\"}]", kNow));
        t.check(!json.ok() && json.error.contains(QLatin1String("JSON")), QStringLiteral("a JSON export: refused, naming the format"),
                json.error);
        // Firefox's Copy All of a request's headers is JSON too, and is told
        // the way that works instead.
        const Result copyAll = keep(CookieImport::parse(
            "{\"Request Headers (1.2 kB)\":{\"headers\":[{\"name\":\"Cookie\",\"value\":\"SAPISID=TESTSAPISID123\"}]}}",
            kNow));
        t.check(!copyAll.ok() && copyAll.error.contains(QLatin1String("Copy All"))
                    && copyAll.error.contains(QLatin1String("cURL")),
                QStringLiteral("headers copied with Copy All (JSON): refused, pointing to Copy as cURL"), copyAll.error);
        const Result ps = keep(CookieImport::parse(
            "$session = New-Object Microsoft.PowerShell.Commands.WebRequestSession\n"
            "$session.Cookies.Add((New-Object System.Net.Cookie(\"SAPISID\", \"TESTSAPISID123\", \"/\", \".youtube.com\")))\n"
            "Invoke-WebRequest -UseBasicParsing -Uri \"https://music.youtube.com/\"", kNow));
        t.check(!ps.ok() && ps.error.contains(QLatin1String("PowerShell")), QStringLiteral("a PowerShell copy: refused"), ps.error);
        const Result empty = keep(CookieImport::parse(" \r\n\t ", kNow));
        t.check(!empty.ok() && empty.error.contains(QLatin1String("empty")), QStringLiteral("nothing at all: refused"), empty.error);
        const Result binary = keep(CookieImport::parse(QByteArray("PK\x03\x04\0\0binary", 12), kNow));
        t.check(!binary.ok(), QStringLiteral("a binary file: refused"), binary.error);
    }

    // — the jar as stored —
    {
        using Info = CookieImport::SessionInfo;
        const QByteArray json = CookieImport::toJson(lf.cookies);
        QList<Cookie> back;
        Info backInfo;
        backInfo.authUser = 5;
        t.check(CookieImport::fromJson(json, &back, &backInfo) && sameJar(back, lf.cookies) && backInfo.isEmpty(),
                QStringLiteral("the jar round-trips through its JSON (%1 bytes)").arg(json.size()));
        t.check(json.contains("\"version\":1") && !json.contains("\"session\""),
                QStringLiteral("with nothing known beside the cookies it is written as version 1, as before"));
        QList<Cookie> high = lf.cookies;
        high[0].value = QByteArray("\x01\x7f\x80\xff", 4);
        QList<Cookie> highBack;
        t.check(CookieImport::fromJson(CookieImport::toJson(high), &highBack) && sameJar(highBack, high),
                QStringLiteral("every byte of a value survives it"));

        Info info;
        info.authUser = 2;
        info.visitorData = kSignedInVisitor;
        info.dataSyncId = kBrandSync;
        const QByteArray v2 = CookieImport::toJson(lf.cookies, info);
        QList<Cookie> back2;
        Info info2;
        t.check(v2.contains("\"version\":1") && v2.contains("\"session\"") && CookieImport::fromJson(v2, &back2, &info2)
                    && sameJar(back2, lf.cookies) && info2 == info,
                QStringLiteral("with the session's index, visitor id and DATASYNC_ID: still version 1, with a session "
                               "part, and they round-trip"));
        // What a build from before the session part reads: version 1 and
        // the cookies, the rest passed over. Such a build deletes a jar it
        // cannot read.
        {
            const QJsonObject old = QJsonDocument::fromJson(v2).object();
            t.check(old.value(QStringLiteral("version")).toInt() == 1 && old.value(QStringLiteral("cookies")).isArray()
                        && old.value(QStringLiteral("cookies")).toArray().size() == lf.cookies.size(),
                    QStringLiteral("so a Monolist from before engine step SI1 still opens it, rather than deleting it"));
        }
        // A jar SI1 wrote, as version 2, is still read whole.
        QList<Cookie> backSi1;
        Info infoSi1;
        t.check(CookieImport::fromJson(QByteArray(v2).replace("\"version\":1", "\"version\":2"), &backSi1, &infoSi1)
                    && sameJar(backSi1, lf.cookies) && infoSi1 == info,
                QStringLiteral("a jar written as version 2 (engine step SI1) is read, its session part too"));
        // A stored part that does not pass is not known; the cookies stay.
        const QByteArray odd = QByteArray(v2).replace(kSignedInVisitor.toLatin1(), "bad id\\r\\nX-Evil: 1")
                                   .replace("\"authUser\":2", "\"authUser\":300");
        QList<Cookie> back3;
        Info info3;
        t.check(CookieImport::fromJson(odd, &back3, &info3) && sameJar(back3, lf.cookies) && info3.visitorData.isEmpty()
                    && info3.authUser == -1 && info3.dataSyncId == kBrandSync,
                QStringLiteral("a stored visitor id with a line break, an index of 300: dropped, the rest kept"));

        QList<Cookie> refused = lf.cookies;
        Info refusedInfo = info;
        t.check(!CookieImport::fromJson("{\"version\":3,\"cookies\":[]}", &refused, &refusedInfo) && refused.isEmpty()
                    && refusedInfo.isEmpty() && !CookieImport::fromJson("not json", &refused)
                    && !CookieImport::fromJson(QByteArray(json).replace("youtube.com", "example.org"), &refused),
                QStringLiteral("another version, not JSON, or another site's cookies: refused, and nothing returned"));
    }

    // — what the session says of itself, checked before it is believed —
    {
        using Info = CookieImport::SessionInfo;
        Info own;
        own.dataSyncId = kOwnSync;
        Info brand;
        brand.dataSyncId = kBrandSync;
        t.check(own.delegatedId().isEmpty() && brand.delegatedId() == QLatin1String("TESTDELEGATED0001")
                    && Info().delegatedId().isEmpty(),
                QStringLiteral("DATASYNC_ID \"<user>||\" names no brand channel; \"<delegated>||<user>\" names the first"));
        t.check(CookieImport::dataSyncIdFrom(kOwnSync) == kOwnSync && CookieImport::dataSyncIdFrom(kBrandSync) == kBrandSync
                    && CookieImport::dataSyncIdFrom(QStringLiteral("||")).isEmpty()
                    && CookieImport::dataSyncIdFrom(QStringLiteral("a|b")).isEmpty()
                    && CookieImport::dataSyncIdFrom(QStringLiteral("a||b||c")).isEmpty()
                    && CookieImport::dataSyncIdFrom(QStringLiteral("a b||")).isEmpty(),
                QStringLiteral("a DATASYNC_ID is two ids around \"||\", or nothing"));
        t.check(CookieImport::authUserFrom("0") == 0 && CookieImport::authUserFrom(" 3 ") == 3
                    && CookieImport::authUserFrom("99") == 99 && CookieImport::authUserFrom("100") == -1
                    && CookieImport::authUserFrom("-1") == -1 && CookieImport::authUserFrom("1a") == -1
                    && CookieImport::authUserFrom("") == -1,
                QStringLiteral("X-Goog-AuthUser is a number from 0 to 99, or unknown"));
        t.check(CookieImport::visitorDataFrom(kSignedInVisitor) == kSignedInVisitor
                    && CookieImport::visitorDataFrom(QStringLiteral("TESTVISITOR\r\nX-Evil: 1")).isEmpty()
                    && CookieImport::visitorDataFrom(QStringLiteral("short")).isEmpty(),
                QStringLiteral("a visitor id is base64 and percent signs, or nothing: never a line break"));
    }

    // — the header sent, host by host —
    {
        // All but SIDCC is the same to each host that has it.
        const auto common = [](const QByteArray &sidcc) {
            return "PREF=TESTVAL-pref-1; LOGIN_INFO=TESTVAL-login-info-2; APISID=TESTVAL-apisid-3; "
                   "SAPISID=TESTSAPISID123; __Secure-1PAPISID=TESTSECURE1PAPISID456; "
                   "__Secure-3PAPISID=TESTSECURE3PAPISID789; HSID=TESTVAL-hsid-4; SSID=TESTVAL-ssid-5; "
                   "SID=TESTVAL-sid-youtube-6; __Secure-1PSID=TESTVAL-1psid-7; __Secure-3PSID=TESTVAL-3psid-8; "
                   "SIDCC=" + sidcc + "; YSC=TESTVAL-ysc-10; EMPTYVAL=";
        };
        // What the one-host jar sent before there were three, byte for byte.
        const QByteArray music = common("TESTVAL-sidcc-music-11");
        const QString api = CookieImport::kApiPath;
        t.check(CookieImport::header(lf.cookies, CookieImport::kMusicHost, api + QStringLiteral("browse"), kNow) == music,
                QStringLiteral("music.youtube.com: the Cookie header as before, byte for byte (compared, not shown); "
                               "its own SIDCC, and none of www's, s's, /watch's or /api/stats's"));
        t.check(CookieImport::header(lf.cookies, CookieImport::kMusicHost, api + QStringLiteral("account/account_menu"), kNow)
                    == music,
                QStringLiteral("the same for every call under /youtubei/v1/"));
        const QByteArray www = common("TESTVAL-sidcc-9") + "; WWWONLY=TESTVAL-www-12";
        t.check(CookieImport::header(lf.cookies, CookieImport::kWwwHost, api + QStringLiteral("player"), kNow) == www,
                QStringLiteral("www.youtube.com: youtube.com's SIDCC, not music's, and its own cookie"));
        t.check(CookieImport::header(lf.cookies, CookieImport::kWwwHost, QStringLiteral("/watch"), kNow)
                    == "WATCHPATH=TESTVAL-watch-13; " + www,
                QStringLiteral("www.youtube.com/watch: the /watch cookie too, first, as the longer path"));
        t.check(CookieImport::header(lf.cookies, CookieImport::kStatsHost, QStringLiteral("/api/stats/playback"), kNow)
                    == "STATSPATH=TESTVAL-statspath-18; " + common("TESTVAL-sidcc-9") + "; STATSONLY=TESTVAL-stats-17",
                QStringLiteral("s.youtube.com/api/stats/playback: its own cookie and /api/stats's, the longer path first"));
        t.check(CookieImport::header(lf.cookies, CookieImport::kStatsHost, QStringLiteral("/api/statsx"), kNow)
                    == common("TESTVAL-sidcc-9") + "; STATSONLY=TESTVAL-stats-17",
                QStringLiteral("a path is matched by whole segments: /api/stats is not sent to /api/statsx"));
        t.check(CookieImport::header(lf.cookies, CookieImport::kMusicHost, api + QStringLiteral("browse"), 1840000000)
                    == "YSC=TESTVAL-ysc-10",
                QStringLiteral("cookies that have expired since are left out of it"));
        const Result pasted = CookieImport::parse(kHeader, kNow);
        const QByteArray pastedMusic = CookieImport::header(pasted.cookies, CookieImport::kMusicHost, api, kNow);
        t.check(!pastedMusic.isEmpty()
                    && CookieImport::header(pasted.cookies, CookieImport::kWwwHost, api, kNow) == pastedMusic
                    && CookieImport::header(pasted.cookies, CookieImport::kStatsHost, QStringLiteral("/api/stats/playback"),
                                            kNow) == pastedMusic,
                QStringLiteral("a pasted Cookie header's cookies (.youtube.com, path /) go to all three alike"));
    }

    // — the jar as a cookies.txt file for yt-dlp —
    {
        QList<Cookie> jar = lf.cookies;
        Cookie google;
        google.name = "SID";
        google.value = "TESTVAL-google-extra";
        google.domain = QStringLiteral("google.com");
        google.secure = true;
        google.expires = 1830000000;
        Cookie expired = google;
        expired.name = "OLDCOOKIE";
        expired.value = "TESTVAL-expired-16";
        expired.domain = QStringLiteral("youtube.com");
        expired.expires = 1600000000;
        Cookie broken = expired;
        broken.name = "BROKEN";
        broken.value = "TESTVAL-broken\n.youtube.com\tTRUE\t/\tTRUE\t0\tINJECTED\tx";
        broken.expires = 1830000000;
        jar << google << expired << broken;
        int written = -1;
        const QByteArray file = CookieImport::toNetscape(jar, kNow, &written);
        t.check(file.startsWith("# Netscape HTTP Cookie File\n") && written == lf.cookies.size(),
                QStringLiteral("the file starts as Python's reader insists, and has one line a cookie (%1)").arg(written));
        t.check(!file.contains("google.com") && !file.contains("TESTVAL-google-extra"),
                QStringLiteral("never a google.com cookie, even one in the jar"));
        t.check(!file.contains("OLDCOOKIE") && !file.contains("BROKEN") && !file.contains("INJECTED"),
                QStringLiteral("nor an expired one, nor one whose value would break its line and start another"));
        const Result back = CookieImport::parse(file, kNow);
        t.check(back.ok() && back.format == Format::Netscape && sameJar(back.cookies, lf.cookies) && back.unreadable == 0
                    && back.duplicates == 0 && back.otherSites == 0,
                QStringLiteral("read back, it is the jar, cookie for cookie"), counts(back) + QStringLiteral("; ") + back.error);
        // Python's MozillaCookieJar refuses a file whose second column is
        // TRUE without a dot on the domain, or the other way about; and
        // yt-dlp refuses an expiry that is not all digits.
        bool consistent = true;
        int lines = 0;
        for (QByteArray line : file.split('\n')) {
            if (line.startsWith("#HttpOnly_"))
                line.remove(0, int(qstrlen("#HttpOnly_")));
            else if (line.startsWith('#') || line.isEmpty())
                continue;
            const QList<QByteArray> fields = line.split('\t');
            ++lines;
            bool digits = !fields.value(4).isEmpty();
            for (const char c : fields.value(4))
                digits = digits && c >= '0' && c <= '9';
            consistent = consistent && fields.size() == 7 && fields.at(0).startsWith('.') == (fields.at(1) == "TRUE")
                         && (fields.at(3) == "TRUE" || fields.at(3) == "FALSE") && digits;
        }
        t.check(consistent && lines == written,
                QStringLiteral("every line has seven columns, a dot exactly where the second says TRUE, and a numeric expiry"));
        t.check(file.contains("#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t1830000000\tLOGIN_INFO\t")
                    && file.contains("\nmusic.youtube.com\tFALSE\t/\tTRUE\t1830000000\tSIDCC\t")
                    && file.contains("\n#HttpOnly_.youtube.com\tTRUE\t/\tTRUE\t0\tYSC\t")
                    && file.contains("\n.youtube.com\tTRUE\t/\tTRUE\t1830000000\tEMPTYVAL\t\n"),
                QStringLiteral("HttpOnly marked, a host-only cookie without its dot, a session cookie's expiry 0, "
                               "an empty value kept"));
        int none = -1;
        t.check(CookieImport::toNetscape({}, kNow, &none).startsWith("# Netscape HTTP Cookie File\n") && none == 0,
                QStringLiteral("an empty jar is the header lines alone"));
        // What yt-dlp writes back: Python's cookie jar leaves a session
        // cookie's expiry empty, where curl and this file write 0.
        QByteArray pythons = file;
        pythons.replace("\t/\tTRUE\t0\tYSC\t", "\t/\tTRUE\t\tYSC\t");
        const Result python = CookieImport::parse(pythons, kNow);
        t.check(pythons != file && python.ok() && sameJar(python.cookies, lf.cookies) && python.unreadable == 0
                    && find(python.cookies, "YSC").expires == 0,
                QStringLiteral("read back as yt-dlp writes it, an empty expiry is a session cookie (0)"),
                counts(python));
    }

    // — SAPISIDHASH: known answers, each SHA-1 computed apart from this code
    // (.NET's SHA1 over "<ts> <sid> <origin>") —
    {
        const QByteArray origin = YtmSession::kOrigin;
        const QByteArray one = YtmSession::sidHash("SAPISIDHASH", kNow, "TESTSAPISID123", origin);
        t.check(one == "SAPISIDHASH 1790000000_f4b52ff9a48e3c8447cf5c2dc974c2c9b0a1e946",
                QStringLiteral("SAPISIDHASH known answer"));
        const QByteArray all = YtmSession::authorization(lf.cookies, kNow, origin);
        t.check(all == "SAPISIDHASH 1790000000_f4b52ff9a48e3c8447cf5c2dc974c2c9b0a1e946 "
                       "SAPISID1PHASH 1790000000_b872625234e084a7ffe7f8544bc00cff94e62daa "
                       "SAPISID3PHASH 1790000000_31dcc68e15800ea041c83c1cbb49e65ba892eddf",
                QStringLiteral("all three schemes, space-separated, in yt-dlp's order"));
        static const QRegularExpression shape(
            QStringLiteral("^SAPISIDHASH \\d+_[0-9a-f]{40} SAPISID1PHASH \\d+_[0-9a-f]{40} SAPISID3PHASH \\d+_[0-9a-f]{40}$"));
        t.check(shape.match(QString::fromLatin1(all)).hasMatch(), QStringLiteral("lower-case hex, 40 digits each"));
        const Result third = CookieImport::parse(
            "LOGIN_INFO=TESTVAL-login-info-2; __Secure-3PAPISID=TESTSECURE3PAPISID789", kNow);
        t.check(YtmSession::authorization(third.cookies, kNow, origin)
                    == "SAPISIDHASH 1790000000_31dcc68e15800ea041c83c1cbb49e65ba892eddf "
                       "SAPISID3PHASH 1790000000_31dcc68e15800ea041c83c1cbb49e65ba892eddf",
                QStringLiteral("without SAPISID, SAPISIDHASH is made from __Secure-3PAPISID"));
        t.check(YtmSession::sidHash("SAPISIDHASH", kNow, "TESTSAPISID123", "https://www.youtube.com")
                    == "SAPISIDHASH 1790000000_f48fb12f67f79b5855f0c7bd9d6ea6702c85032d",
                QStringLiteral("the origin is part of the hash (www.youtube.com's differs)"));
        t.check(YtmSession::authorization({}, kNow, origin).isEmpty(), QStringLiteral("no SAPISID of any kind: no header"));
    }

    // — no value in any message —
    {
        QStringList found;
        for (const QString &message : std::as_const(messages))
            found << leaks(message);
        t.check(found.isEmpty(), QStringLiteral("no cookie value in any of %1 errors and summaries").arg(messages.size()),
                found.join(QStringLiteral(", ")));
    }
    return t.finish();
}

